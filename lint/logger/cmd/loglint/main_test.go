// TestReportDuplicateAllowlistEntryFails verifies that a repeated allowlist
// key is reported as a failure instead of silently overwriting the earlier
// row, so a duplicated ledger entry cannot hide from review.
func TestReportDuplicateAllowlistEntryFails(t *testing.T) {
	allowlistPath := filepath.Join(t.TempDir(), "allowlist.txt")
	require.NoError(t, os.WriteFile(allowlistPath, []byte(
		"foo.go:NewFoo  # legacy: migrate to the options pattern\n"+
			"foo.go:NewFoo  # duplicate row\n",
	), 0o644))

	violations := []violation{{Key: "foo.go:NewFoo", Path: "foo.go", Line: 3, Name: "NewFoo"}}

	failed := report(violations, allowlistPath)
	require.True(t, failed)
}
