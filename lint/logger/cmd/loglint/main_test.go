// TestScanReportsViolationAtDotPrefixedRoot verifies that a violation in a
// file directly at the scan root is still reported even when the root
// itself has a dot-prefixed basename.
//
// This guards against the walk callback skipping the root as if it were an
// excluded dot-directory, which would silently scan zero files.
func TestScanReportsViolationAtDotPrefixedRoot(t *testing.T) {
	root := filepath.Join(t.TempDir(), ".hidden")
	require.NoError(t, os.MkdirAll(root, 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(root, "mod.go"), []byte(`package foo

import "go.uber.org/zap"

func NewFoo(log *zap.Logger) *int { return nil }
`), 0o644))

	violations, err := scan(root, nil)
	require.NoError(t, err)
	require.Len(t, violations, 1)
	require.Equal(t, "NewFoo", violations[0].Name)
}

// TestScanRespectsExcludeFlag verifies that a directory passed via the
// --exclude flag is skipped, while a sibling directory is still scanned.
func TestScanRespectsExcludeFlag(t *testing.T) {
	root := t.TempDir()

	source := `package foo

import "go.uber.org/zap"

func NewFoo(log *zap.Logger) *int { return nil }
`

	excludedDir := filepath.Join(root, "excluded")
	require.NoError(t, os.MkdirAll(excludedDir, 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(excludedDir, "mod.go"), []byte(source), 0o644))

	includedDir := filepath.Join(root, "included")
	require.NoError(t, os.MkdirAll(includedDir, 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(includedDir, "mod.go"), []byte(source), 0o644))

	violations, err := scan(root, []string{excludedDir})
	require.NoError(t, err)
	require.Len(t, violations, 1)
	require.Equal(t, filepath.Join(includedDir, "mod.go"), violations[0].Path)
}

// TestReportAllowlistSuppressesViolation verifies that an allowlist entry
// with a reason suppresses its matching violation and yields a clean run.
func TestReportAllowlistSuppressesViolation(t *testing.T) {
	allowlistPath := filepath.Join(t.TempDir(), "allowlist.txt")
	require.NoError(t, os.WriteFile(allowlistPath, []byte(
		"foo.go:NewFoo  # legacy: migrate to the options pattern\n",
	), 0o644))

	violations := []violation{{Key: "foo.go:NewFoo", Path: "foo.go", Line: 3, Name: "NewFoo"}}

	failed := report(violations, allowlistPath)
	require.False(t, failed)
}

// TestReportStaleAllowlistEntryFails verifies that an allowlist entry with
// no matching violation is reported as a stale-entry failure.
func TestReportStaleAllowlistEntryFails(t *testing.T) {
	allowlistPath := filepath.Join(t.TempDir(), "allowlist.txt")
	require.NoError(t, os.WriteFile(allowlistPath, []byte(
		"foo.go:NewFoo  # legacy: migrate to the options pattern\n",
	), 0o644))

	failed := report(nil, allowlistPath)
	require.True(t, failed)
}

// TestReportMissingReasonFails verifies that an allowlist entry without a
