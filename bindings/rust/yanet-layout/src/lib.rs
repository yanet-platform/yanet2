//! Generator of the Go views of the shared-memory layouts the SDK's module
//! crates define, from the layout description of their roots.
//!
//! A generator crate lists the roots and constants of its modules and calls
//! [`generate`]; `make native-layout` runs it with `cargo run`, built for the
//! host, as the plugins are. The Go package it writes holds one generic shape
//! of each SDK field type the roots reach, a view of each struct with Rust's
//! padding, and a test that pins every size, offset and alignment the views
//! take from Rust. A generic struct reached in several instances has a view of
//! each, named with a suffix of its type arguments.

use core::fmt::Write as _;
use std::{env::consts::ARCH, fs, path::Path};

use yanet_sdk::layout::{Field, Kind, Node};

/// Writes the Go views of the roots and the typed constants, and their test,
/// as `zz_layout_<arch>.go` and `zz_layout_<arch>_test.go` into the directory
/// of the Go package of the given import path.
///
/// Fails on a type without a layout description that holds bytes and on an
/// atomic narrower than Go's, naming where it was reached, and on two types
/// under one Go name; a file that already holds its output is left alone.
pub fn generate(
    dir: &Path,
    import: &str,
    roots: &[&'static Node],
    constants: &[(&str, Constant)],
) -> Result<(), String> {
    let goarch = match ARCH {
        "x86_64" => "amd64",
        "aarch64" => "arm64",
        other => return Err(format!("no Go views for the architecture {other}")),
    };
    let mut views = Views::default();
    for root in roots {
        views.reach(root, "a root", false)?;
    }
    views.check_names()?;
    let package = &import[import.rfind('/').map_or(0, |idx| idx + 1)..];
    let header = format!("// Code generated by yanet-layout. DO NOT EDIT.\n\n//go:build linux && {goarch}\n\n");
    let view = views.render(&header, package, constants);
    let test = views.render_test(&header, package, import);
    for (suffix, source) in [("", view), ("_test", test)] {
        let path = dir.join(format!("zz_layout_{goarch}{suffix}.go"));
        if fs::read_to_string(&path).ok().as_deref() != Some(source.as_str()) {
            fs::write(&path, source).map_err(|err| format!("{}: {err}", path.display()))?;
        }
    }
    Ok(())
}

/// A constant of the Go views, of the Go type its variant names.
pub enum Constant {
    /// A Go `uint32`.
    U32(u32),
    /// A Go `uint64`.
    U64(u64),
    /// A Go `string`.
    Str(&'static str),
}

/// The structs and the field types the roots reach, each declared once, in
/// the order they are reached.
#[derive(Default)]
struct Views {
    /// Each struct instance, and one instance of each field type, whose
    /// members give its shape.
    declared: Vec<&'static Node>,
    /// Every distinct field type instance, which the test pins.
    instances: Vec<&'static Node>,
}

impl Views {
    /// Records a type and everything it reaches, refusing what has no Go
    /// view and naming where it was reached; the members of a field type's
    /// shape are no instance the test pins.
    fn reach(&mut self, node: &'static Node, context: &str, generic: bool) -> Result<(), String> {
        match node.kind {
            Kind::Array { elem, .. } => self.reach(elem, context, generic)?,
            Kind::Ptr { target } => self.reach(target, context, generic)?,
            Kind::Struct { name, .. } => {
                if !self.declared.contains(&node) {
                    self.declared.push(node);
                    for field in members(node) {
                        self.reach(field.ty, &format!("{}.{}", go_name(name), field.name), generic)?;
                    }
                }
            }
            Kind::Edge { kind, args, .. } => {
                let name = camel(kind);
                let shape = self
                    .declared
                    .iter()
                    .find(|seen| matches!(seen.kind, Kind::Edge { kind: other, .. } if other == kind));
                match shape {
                    // Instances of one field type differ in their arguments
                    // alone.
                    Some(seen) if same_shape(seen, node) => {}
                    Some(_) => return Err(format!("{context}: no Go view of two field types named {name}")),
                    None => {
                        self.declared.push(node);
                        for field in members(node) {
                            self.reach(field.ty, &format!("{name}.{}", field.name), true)?;
                        }
                    }
                }
                if !generic && !self.instances.contains(&node) {
                    self.instances.push(node);
                }
                for arg in args {
                    self.reach(arg, context, generic)?;
                }
            }
            Kind::Int { atomic: true, .. } if node.size < 4 => {
                return Err(format!("{context}: no Go view of an atomic of {} bits", node.size * 8));
            }
            Kind::Int { .. } | Kind::Param { .. } | Kind::C { .. } => {}
            Kind::Opaque => return Err(format!("{context}: no Go view of a type without a layout description")),
        }
        Ok(())
    }

    /// Refuses two declarations under one Go name: structs of one name from
    /// two paths, a struct named as a field type, or instances whose type
    /// arguments give one suffix.
    fn check_names(&self) -> Result<(), String> {
        let mut names: Vec<_> = self.declared.iter().map(|node| self.name(node)).collect();
        names.sort_unstable();
        match names.windows(2).find(|pair| pair[0] == pair[1]) {
            Some(pair) => Err(format!("no Go view of two types named {}", pair[0])),
            None => Ok(()),
        }
    }

    /// The Go name of a struct or of a field type's shape.
    ///
    /// A struct is named by the last segment of its path, and an instance
    /// of a generic struct reached in several instances also by its type
    /// arguments: `Pair4x16` for one over a 4-byte and a 16-byte address.
    fn name(&self, node: &Node) -> String {
        match node.kind {
            Kind::Struct { name: path, args, .. } => {
                let instances = self
                    .declared
                    .iter()
                    .filter(|seen| matches!(seen.kind, Kind::Struct { name, .. } if name == path))
                    .count();
                if instances < 2 {
                    return go_name(path);
                }
                let suffix: Vec<_> = args.iter().map(|arg| self.suffix(arg)).collect();
                go_name(path) + &suffix.join("x")
            }
            Kind::Edge { kind, .. } => camel(kind),
            _ => unreachable!("only a struct or a field type is declared"),
        }
    }

    /// The part of an instance's name that a type argument gives: the
    /// length of an array of bytes, as of an address, and the Go name of
    /// anything else, without its punctuation.
    fn suffix(&self, node: &Node) -> String {
        match node.kind {
            Kind::Array { len, elem } if matches!(elem.kind, Kind::Int { atomic: false, .. }) && elem.size == 1 => {
                len.to_string()
            }
            Kind::Array { len, elem } => format!("{len}{}", self.suffix(elem)),
            Kind::Int { signed, atomic } => {
                let atomic = if atomic { "Atomic" } else { "" };
                let sign = if signed { "Int" } else { "Uint" };
                format!("{atomic}{sign}{}", node.size * 8)
            }
            Kind::Struct { .. } => self.name(node),
            Kind::Edge { kind, args, .. } => {
                let args: String = args.iter().map(|arg| self.suffix(arg)).collect();
                camel(kind) + &args
            }
            Kind::Ptr { target } => format!("Ptr{}", self.suffix(target)),
            Kind::Param { index } => format!("T{index}"),
            Kind::C { name } => camel(name),
            Kind::Opaque => "Opaque".to_owned(),
        }
    }

    /// The views: the constants, then the shape of each field type and each
    /// struct with its alignment.
    fn render(&self, header: &str, package: &str, constants: &[(&str, Constant)]) -> String {
        let mut body = String::new();
        if !constants.is_empty() {
            body.push_str("\n// Values the crates name, from the build of the views.\n");
        }
        for (name, value) in constants {
            let (ty, value) = match value {
                Constant::U32(value) => ("uint32", value.to_string()),
                Constant::U64(value) => ("uint64", value.to_string()),
                Constant::Str(value) => ("string", go_string(value)),
            };
            let _ = writeln!(body, "const {} {ty} = {value}", camel(&name.to_lowercase()));
        }
        for node in &self.declared {
            let name = self.name(node);
            match node.kind {
                Kind::Edge { kind, args, .. } => {
                    let params: Vec<_> = (0..args.len()).map(|idx| format!("T{idx}")).collect();
                    let params = if params.is_empty() {
                        String::new()
                    } else {
                        format!("[{} any]", params.join(", "))
                    };
                    let _ = writeln!(body, "\n// {name} is the SDK field type {kind}.");
                    render_struct(self, &mut body, node, &params);
                }
                Kind::Struct { name: path, .. } => {
                    let (size, align) = (node.size, node.align);
                    let _ = writeln!(
                        body,
                        "\n// {name} is the Rust struct {path},\n// {size} bytes aligned to {align}."
                    );
                    render_struct(self, &mut body, node, "");
                    let _ = writeln!(
                        body,
                        "\n// {name}Align is the alignment Rust gives {name}.\nconst {name}Align = {align}"
                    );
                }
                _ => unreachable!("only a struct or a field type is declared"),
            }
        }
        format!("{header}package {package}\n\n{}{body}", imports(&body, &[]))
    }

    /// The test that compares every size and offset Go gives the views with
    /// the one Rust gave, and that Go's alignment of a struct divides Rust's.
    fn render_test(&self, header: &str, package: &str, import: &str) -> String {
        let qualifier = format!("{package}.");
        let mut cases = String::new();
        let mut case = |name: String, got: String, want: usize| {
            let _ = writeln!(cases, "\t\t{{{name:?}, {got}, {want}}},");
        };
        let structs = self
            .declared
            .iter()
            .filter(|node| matches!(node.kind, Kind::Struct { .. }));
        for node in structs.chain(&self.instances) {
            let (name, value) = (
                go_type(self, node, ""),
                format!("{}{{}}", go_type(self, node, &qualifier)),
            );
            for field in members(node) {
                let selector = format!("{value}.{}", go_field(field.name));
                let member = format!("{name}.{}", go_field(field.name));
                let offset = format!("unsafe.Offsetof({selector})");
                case(format!("{member} offset"), offset, field.offset);
                // A member holding a type argument by value takes the
                // argument's size.
                let size = match (&field.ty.kind, &node.kind) {
                    (Kind::Param { index }, Kind::Edge { args, .. }) => args[*index].size,
                    _ => field.ty.size,
                };
                case(format!("{member} size"), format!("unsafe.Sizeof({selector})"), size);
            }
            case(format!("{name} size"), format!("unsafe.Sizeof({value})"), node.size);
            if let Kind::Struct { .. } = node.kind {
                case(
                    format!("{name} align"),
                    format!("{qualifier}{name}Align % unsafe.Alignof({value})"),
                    0,
                );
            }
        }
        let body = format!(
            "// Test_Layout_MatchesRust verifies that every view has the size, field\n\
             // offsets and field sizes Rust gave its type, and an alignment Rust's is a\n\
             // multiple of.\n\
             func Test_Layout_MatchesRust(t *testing.T) {{\n\
             \tcases := []struct {{\n\t\tname string\n\t\tgot  uintptr\n\t\twant uintptr\n\t}}{{\n\
             {cases}\t}}\n\
             \tfor _, tc := range cases {{\n\
             \t\tt.Run(tc.name, func(t *testing.T) {{\n\t\t\trequire.Equal(t, tc.want, tc.got)\n\t\t}})\n\t}}\n}}\n"
        );
        let imports = imports(
            &body,
            &["testing", "unsafe", "github.com/stretchr/testify/require", import],
        );
        format!("{header}package {package}_test\n\n{imports}\n{body}")
    }
}

/// The fields of a struct or the members of a field type, in the order of
/// their offsets.
///
/// A zero-sized field holds no data and is left out: Go pads a struct that
/// ends in one, Rust does not. A member holding a type argument by value
/// stays, whatever the argument's size.
fn members(node: &Node) -> Vec<&'static Field> {
    let fields = match node.kind {
        Kind::Struct { fields, .. } => fields,
        Kind::Edge { members, .. } => members,
        _ => unreachable!("only a struct or a field type is declared"),
    };
    let mut fields: Vec<_> = fields
        .iter()
        .filter(|field| field.ty.size != 0 || matches!(field.ty.kind, Kind::Param { .. }))
        .collect();
    fields.sort_by_key(|field| field.offset);
    fields
}

/// Whether two field type instances share one shape: their number of type
/// arguments, their members and their size and alignment.
///
/// A member holding a type argument by value is placed by the argument's
/// alignment, so its offset, and the size and the alignment of the
/// instance, differ between the instances of one shape.
fn same_shape(left: &Node, right: &Node) -> bool {
    let arity = |node: &Node| match node.kind {
        Kind::Edge { args, .. } => args.len(),
        _ => 0,
    };
    let by_value = |field: &Field| matches!(field.ty.kind, Kind::Param { .. });
    let (left_members, right_members) = (members(left), members(right));
    let placed_by_argument = left_members.iter().any(|field| by_value(field));
    arity(left) == arity(right)
        && left_members.len() == right_members.len()
        && left_members.iter().zip(&right_members).all(|(left, right)| {
            (left.name, left.ty) == (right.name, right.ty) && (left.offset == right.offset || by_value(left))
        })
        && (placed_by_argument || (left.size, left.align) == (right.size, right.align))
}

/// Writes the Go struct of a struct or a field type's shape, with the given
/// type parameters and padding where Rust leaves bytes.
///
/// A member holding a type argument by value gets no padding before or after
/// it: Go places it by the alignment of the argument's view, as Rust places it
/// by the argument's, which the test pins per instance.
fn render_struct(views: &Views, out: &mut String, node: &Node, params: &str) {
    let mut lines = Vec::new();
    let mut cursor = 0;
    // Go places a member held by value, and what follows it, by itself.
    let mut placed_by_go = false;
    for field in members(node) {
        placed_by_go |= matches!(field.ty.kind, Kind::Param { .. });
        if !placed_by_go && field.offset > cursor {
            lines.push(("_".to_owned(), format!("[{}]byte", field.offset - cursor)));
        }
        lines.push((go_field(field.name), go_type(views, field.ty, "")));
        cursor = field.offset + field.ty.size;
    }
    if !placed_by_go && node.size > cursor {
        lines.push(("_".to_owned(), format!("[{}]byte", node.size - cursor)));
    }
    let width = lines.iter().map(|(field, _)| field.len()).max().unwrap_or(0);
    let _ = writeln!(out, "type {}{params} struct {{", views.name(node));
    for (field, ty) in lines {
        let _ = writeln!(out, "\t{field:width$} {ty}");
    }
    out.push_str("}\n");
}

/// The import block of a Go source: the given imports, and each shared
/// package the source names as a qualifier.
fn imports(source: &str, always: &[&str]) -> String {
    let mut paths = always.to_vec();
    for (package, path) in [
        ("atomic", "sync/atomic"),
        ("layout", "github.com/yanet-platform/yanet2/controlplane/native/layout"),
        ("shm", "github.com/yanet-platform/yanet2/controlplane/native/shm"),
    ] {
        if [" ", "[", "]"]
            .iter()
            .any(|before| source.contains(&format!("{before}{package}.")))
        {
            paths.push(path);
        }
    }
    paths.sort();
    let lines: String = paths.iter().map(|path| format!("\t{path:?}\n")).collect();
    format!("import (\n{lines})\n")
}

/// The Go type of a reached type, with the generated declarations qualified
/// where another package names them.
fn go_type(views: &Views, node: &Node, qualifier: &str) -> String {
    match node.kind {
        Kind::Int { signed, atomic } => {
            let bits = node.size * 8;
            match (atomic, signed) {
                (true, true) => format!("atomic.Int{bits}"),
                (true, false) => format!("atomic.Uint{bits}"),
                (false, true) => format!("int{bits}"),
                (false, false) => format!("uint{bits}"),
            }
        }
        Kind::Array { len, elem } => format!("[{len}]{}", go_type(views, elem, qualifier)),
        Kind::Struct { .. } | Kind::Edge { args: [], .. } => qualifier.to_owned() + &views.name(node),
        Kind::Edge { kind, args, .. } => {
            let args: Vec<_> = args.iter().map(|arg| go_type(views, arg, qualifier)).collect();
            format!("{qualifier}{}[{}]", camel(kind), args.join(", "))
        }
        Kind::Ptr { target } => format!("shm.Ptr[{}]", go_type(views, target, qualifier)),
        Kind::Param { index } => format!("T{index}"),
        Kind::C { name } => format!("layout.{}", camel(name)),
        Kind::Opaque => unreachable!("an opaque type is refused when reached"),
    }
}

/// The Go name of a struct: the last segment of its path, a raw identifier
/// without its prefix.
fn go_name(path: &str) -> String {
    let name = path.rsplit("::").next().unwrap_or(path);
    name.strip_prefix("r#").unwrap_or(name).to_owned()
}

/// The Go name of a field or a member, a raw identifier without its prefix.
fn go_field(name: &str) -> String {
    let name = name.strip_prefix("r#").unwrap_or(name);
    match name {
        "id" => "ID".to_owned(),
        _ => camel(name),
    }
}

/// A Go string literal of the value.
fn go_string(value: &str) -> String {
    let escaped: String = value
        .chars()
        .map(|char| match char {
            '"' | '\\' => format!("\\{char}"),
            char if char.is_control() => format!("\\u{:04x}", u32::from(char)),
            char => char.to_string(),
        })
        .collect();
    format!("\"{escaped}\"")
}

/// `snake_case` as `CamelCase`.
fn camel(name: &str) -> String {
    name.split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .into_iter()
                .flat_map(char::to_uppercase)
                .chain(chars)
                .collect::<String>()
        })
        .collect()
}

