#!/usr/bin/env python3

import argparse
import json
import os
from pathlib import Path
import re
import sys
import tempfile

NAME = "zz_yanet_cgo.go"
PROBE_PREFIX = "cgo-link-"
PACKAGE = re.compile(r"^package\s+([A-Za-z_][A-Za-z0-9_]*)", re.M)
TAG = re.compile(r"[A-Za-z0-9_.]+")
# The ASCII bytes go/build accepts in a #cgo argument; any other ASCII byte
# makes every build of the package fail with "malformed #cgo argument".
SAFE = set("+-.,/0123456789=ABCDEFGHIJKLMNOPQRSTUVWXYZ_abcdefghijklmnopqrstuvwxyz:$@%! ~^")


def probe_name(package):
    return PROBE_PREFIX + package.replace("/", "__")


def quote(word):
    """Quote a word the way the Go toolchain splits #cgo flags."""
    unsafe = sorted({c for c in word if c not in SAFE and ord(c) < 0x80})
    if unsafe:
        raise ValueError(f"cgo rejects {''.join(unsafe)!r} in {word}")
    return f'"{word}"' if " " in word else word


def package_name(directory):
    for path in sorted(directory.glob("*.go")):
        if path.name.endswith("_test.go") or path.name == NAME:
            continue
        text = path.read_text()
        if 'import "C"' in text:
            match = PACKAGE.search(text)
            if match:
                return match.group(1)
    raise ValueError("no CGO source")


def link_words(build_root, target):
    """The archives and system libraries meson put on the probe's link line."""
    for source in target["target_sources"]:
        if "linker" not in source:
            continue
        archives, system = [], []
        for word in source["parameters"]:
            if word in ("-Wl,--whole-archive", "-Wl,--no-whole-archive"):
                raise ValueError("a whole archive cannot be expressed in #cgo LDFLAGS")
            if word.endswith(".a") and not word.startswith("-"):
                path = Path(word)
                path = (path if path.is_absolute() else build_root / path).resolve()
                if path not in archives:
                    archives.append(path)
            elif (word.startswith("-l") or word == "-pthread") and word not in system:
                system.append(word)
        return archives, system
    raise ValueError(f"{target['name']}: no link step in the introspection data")


def render(name, directory, build_root, archives, system, tag=None):
    """The package's generated #cgo flags.

    Archives are named relative to the package directory, as -L directories
    and -l: file names, so the file stays valid wherever the checkout is
    mounted and the checkout's own path never reaches cgo's argument check.
    A package built under a tag gets the constraint in its generated file too.
    """
    seen = {}
    for archive in archives:
        if seen.setdefault(archive.name, archive) != archive:
            raise ValueError(f"two archives named {archive.name}: {seen[archive.name]}, {archive}")
    dirs = []
    for archive in archives:
        relative = os.path.relpath(archive.parent, directory)
        if relative not in dirs:
            dirs.append(relative)
    lines = [f"//go:build {tag}", ""] if tag else []
    lines += [
        "// Code generated by scripts/go_cgo_flags.py from the meson link closure. DO NOT EDIT.",
        f"// Build directory: {os.path.relpath(build_root, directory)}",
        "",
        f"package {name}",
        "",
    ]
    if archives:
        lines.append("// #cgo LDFLAGS: " + " ".join(quote("-L" + d) for d in dirs))
        lines.append("// #cgo LDFLAGS: " + " ".join(
            ["-Wl,--start-group"] + [quote("-l:" + a.name) for a in archives] + ["-Wl,--end-group"]
        ))
    if system:
        lines.append("// #cgo LDFLAGS: " + " ".join(
            ["-Wl,--push-state", "-Wl,--as-needed"] + system + ["-Wl,--pop-state"]
        ))
    lines += ['import "C"', ""]
    return "\n".join(lines).encode()


def write(path, content):
    try:
        if path.read_bytes() == content:
            return
    except FileNotFoundError:
        pass
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as output:
            os.fchmod(output.fileno(), 0o644)
            output.write(content)
        os.replace(temporary, path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def main():
    parser = argparse.ArgumentParser(
        description="Publish the meson link closure of CGO packages as #cgo flags."
    )
    parser.add_argument("--root", required=True, type=Path)
    parser.add_argument("--build-root", required=True, type=Path)
    parser.add_argument("--stamp", type=Path)
    parser.add_argument(
        "--archive", nargs=2, action="append", default=[], metavar=("PACKAGE", "PATH"),
        help="an external archive the package links as it is",
    )
    parser.add_argument(
        "--build-tag", nargs=2, action="append", default=[], metavar=("PACKAGE", "TAG"),
        help="the build constraint of every Go file of the package",
    )
    parser.add_argument(
        "packages", nargs="+",
        help="CGO package directories; a package without a probe loses its file",
    )
    args = parser.parse_args()
    root = args.root.resolve(strict=True)
    build_root = args.build_root.resolve(strict=True)
    # A build/ that links elsewhere stays build/ in the flags, so they keep
    # naming the tree the way the checkout sees it.
    in_tree = root / "build"
    shown_root = in_tree if in_tree.resolve() == build_root else build_root
    targets = {}
    for target in json.loads((build_root / "meson-info" / "intro-targets.json").read_text()):
        defined_in = Path(target["defined_in"]).resolve()
        if target["name"].startswith(PROBE_PREFIX) and root in defined_in.parents:
            targets[target["name"]] = target
    external = {}
    for package, path in args.archive:
        external.setdefault(package, []).append(Path(path).resolve())
    tags = {}
    for package, tag in args.build_tag:
        if not TAG.fullmatch(tag):
            print(f"go_cgo_flags: {package}: bad build tag {tag!r}", file=sys.stderr)
            return 1
        tags[package] = tag
    for package in args.packages:
        directory = root / package
        try:
            target = targets.get(probe_name(package))
            archives, system = [], []
            if target is not None:
                archives, system = link_words(build_root, target)
            archives += [a for a in external.get(package, []) if a not in archives]
            if not (archives or system):
                (directory / NAME).unlink(missing_ok=True)
                continue
            archives = [
                shown_root / a.relative_to(build_root) if build_root in a.parents else a
                for a in archives
            ]
            write(directory / NAME, render(
                package_name(directory), directory, shown_root, archives, system,
                tags.get(package),
            ))
        except (OSError, ValueError) as error:
            print(f"go_cgo_flags: {package}: {error}", file=sys.stderr)
            return 1
    if args.stamp:
        write(args.stamp, b"")
    return 0


if __name__ == "__main__":
    sys.exit(main())
